@router.get("/status", response_model=CrawlerStatusResponse)
async def get_crawler_status(task_id: str | None = None):
    """Get crawler status"""
    try:
        return crawler_manager.get_status(task_id)
    except CrawlerTaskConflict as exc:
        raise HTTPException(status_code=409, detail=str(exc)) from exc


@router.get("/logs")
async def get_logs(limit: int = 100):
    """Get recent logs"""
    logs = crawler_manager.logs[-limit:] if limit > 0 else crawler_manager.logs
    return {"logs": [log.model_dump() for log in logs]}


@router.get("/qrcode")
async def get_login_qrcode():
    """Return the QR code generated by the current running task."""
    if (
        crawler_manager.status != "running"
        or crawler_manager.started_at is None
        or not LOGIN_QRCODE_PATH.is_file()
    ):
        raise HTTPException(status_code=404, detail="Login QR code is not ready")

    stat = LOGIN_QRCODE_PATH.stat()
    if stat.st_mtime < crawler_manager.started_at.timestamp():
        raise HTTPException(status_code=404, detail="Login QR code is not ready")

    return FileResponse(
        LOGIN_QRCODE_PATH,
        media_type="image/png",
        headers={
            "Cache-Control": "no-store",
            "X-QR-Version": str(stat.st_mtime_ns),
        },
    )


@router.post("/qrcode/refresh")
async def refresh_login_qrcode():
    """Ask the running Kuaishou login task to publish a fresh QR code."""
    config = crawler_manager.current_config
    if (
        crawler_manager.status != "running"
        or config is None
        or config.platform.value != "ks"
        or config.login_type.value != "qrcode"
    ):
        raise HTTPException(
            status_code=409,
            detail="Kuaishou QR code login is not running",
        )
    LOGIN_QRCODE_REFRESH_PATH.parent.mkdir(parents=True, exist_ok=True)
    LOGIN_QRCODE_REFRESH_PATH.touch()
    return {"status": "ok"}
