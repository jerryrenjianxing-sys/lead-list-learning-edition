from fastapi import APIRouter, HTTPException
from fastapi.responses import FileResponse

from ..schemas import CrawlerStartRequest, CrawlerStatusResponse, CrawlerStopRequest
from ..services import crawler_manager
from ..services.crawler_manager import CrawlerTaskCancelled, CrawlerTaskConflict
from tools.crawler_util import LOGIN_QRCODE_PATH, LOGIN_QRCODE_REFRESH_PATH

router = APIRouter(prefix="/crawler", tags=["crawler"])


@router.post("/start")
async def start_crawler(request: CrawlerStartRequest):
    """Start crawler task"""
    try:
        success = await crawler_manager.start(request)
    except CrawlerTaskCancelled as exc:
        raise HTTPException(status_code=409, detail=str(exc)) from exc
    if not success:
        # A running task owns the process until it finishes or stops.
        if crawler_manager.process and crawler_manager.process.poll() is None:
            raise HTTPException(
                status_code=409,
                detail=f"Crawler task {crawler_manager.current_task_id} is already running",
            )
        raise HTTPException(status_code=500, detail="Failed to start crawler")

    return {
        "status": "ok",
        "message": "Crawler started successfully",
        "task_id": request.task_id,
    }


@router.post("/stop")
async def stop_crawler(request: CrawlerStopRequest):
    """Stop crawler task"""
    if (
        crawler_manager.process
        and crawler_manager.process.poll() is None
        and request.task_id != crawler_manager.current_task_id
    ):
        raise HTTPException(status_code=409, detail="Crawler task identity mismatch")
    try:
        success = await crawler_manager.stop(request.task_id)
    except CrawlerTaskConflict as exc:
        raise HTTPException(status_code=409, detail=str(exc)) from exc
    if not success:
        if crawler_manager.status == "error":
            raise HTTPException(
                status_code=500,
                detail=crawler_manager.error_message or "Failed to stop crawler",
            )
        if not crawler_manager.process or crawler_manager.process.poll() is not None:
            raise HTTPException(status_code=400, detail="No crawler is running")
        raise HTTPException(status_code=500, detail="Failed to stop crawler")

    return {
        "status": "ok",
        "message": "Crawler stopped successfully",
        "task_id": request.task_id,
    }


@router.post("/recover-xhs/{task_id}")
async def recover_xhs(task_id: str):
    """Continue the same Xiaohongshu task after manual verification."""
    try:
        success = await crawler_manager.recover_xhs(task_id)
    except CrawlerTaskConflict as exc:
        raise HTTPException(status_code=409, detail=str(exc)) from exc
    if not success:
        raise HTTPException(status_code=404, detail="No recoverable Xiaohongshu task")
    return {"status": "ok", "task_id": task_id}


